<script>
    document.addEventListener('DOMContentLoaded', function () {
        const btnToggle = document.getElementById('btn-toggle-daily');
        const textToggle = document.getElementById('text-toggle-daily');
        const hiddenItems = document.querySelectorAll('.daily-item-hidden');
        
        if (btnToggle) {
            let isExpanded = false;
            
            btnToggle.addEventListener('click', function () {
                isExpanded = !isExpanded;
                
                hiddenItems.forEach((item) => {
                    if (isExpanded) {
                        item.classList.remove('hidden');
                        setTimeout(() => {
                            item.classList.remove('opacity-0', 'scale-95');
                            item.classList.add('opacity-100', 'scale-100');
                        }, 50);
                    } else {
                        item.classList.remove('opacity-100', 'scale-100');
                        item.classList.add('opacity-0', 'scale-95');
                        setTimeout(() => {
                            item.classList.add('hidden');
                        }, 400);
                    }
                });
                
                textToggle.textContent = isExpanded ? 'Sembunyikan Menu Daily ↩️' : 'Lihat Semua Daily Menu 📂';
            });
        }
    });
</script>